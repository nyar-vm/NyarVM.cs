    #region 嵌套模式分析

    /// <summary>
    ///     收集模式树中所有嵌套的非叶子子模式（用于生成匹配辅助方法）
    /// </summary>
    private static List<NestedPatternInfo> CollectNestedPatterns(PatternNode root)
    {
        var result = new List<NestedPatternInfo>();
        CollectNestedPatternsRecursive(root, result);
        return result;
    }

    private static void CollectNestedPatternsRecursive(PatternNode node, List<NestedPatternInfo> result)
    {
        foreach (var child in node.Children)
            if (child.IsInfixSemantic && child.Children.Count == 2)
            {
                var directVars = child.GetDirectVarNames();
                if (directVars.Count > 0)
                    result.Add(new NestedPatternInfo
                    {
                        OperatorString = child.OperatorString!,
                        IsInfixSemantic = true,
                        BoundVarNames = directVars
                    });

                // 嵌套的子节点中可能还有更深层的嵌套
                CollectNestedPatternsRecursive(child, result);
            }
            else if (child.IsPrefixSemantic && child.Children.Count == 1)
            {
                var directVars = child.GetDirectVarNames();
                if (directVars.Count > 0)
                    result.Add(new NestedPatternInfo
                    {
                        OperatorString = child.OperatorString!,
                        IsInfixSemantic = false,
                        BoundVarNames = directVars
                    });

                CollectNestedPatternsRecursive(child, result);
            }
    }

    /// <summary>
    ///     生成嵌套模式匹配辅助方法
    /// </summary>
    private static void GenerateNestedMatchHelper(StringBuilder sb, NestedPatternInfo info, string indent)
    {
        var varParams = string.Join(", ", info.BoundVarNames.Select(v => $"ref Id __var_{v}"));
        var methodName = info.HelperMethodName;

        sb.AppendLine($"{indent}/// <summary>");
        sb.AppendLine($"{indent}///     匹配内层{info.OperatorString}运算并绑定变量 {string.Join(", ", info.BoundVarNames)}");
        sb.AppendLine($"{indent}/// </summary>");
        sb.AppendLine(
            $"{indent}private static bool {methodName}(EGraph<Oa> egraph, Id childId, {varParams})");
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    foreach (var __inner_node in egraph.get_nodes(childId))");
        sb.AppendLine($"{indent}    {{");

        if (info.IsInfixSemantic)
        {
            var oaPattern = GetCoreInfixMatchPattern(info.OperatorString, "__il", "__ir", true);
            if (oaPattern is not null)
                sb.AppendLine(
                    $"{indent}        if (__inner_node is {oaPattern})");
            else
                sb.AppendLine($"{indent}        if (false)");
        }
        else
        {
            var oaPattern = GetCorePrefixMatchPattern(info.OperatorString, "__iop", true);
            if (oaPattern is not null)
                sb.AppendLine(
                    $"{indent}        if (__inner_node is {oaPattern})");
            else
                sb.AppendLine($"{indent}        if (false)");
        }

        sb.AppendLine($"{indent}        {{");

        for (var i = 0; i < info.BoundVarNames.Count; i++)
        {
            var childExpr = info.IsInfixSemantic
                ? i == 0 ? "__il" : "__ir"
                : "__iop";
            sb.AppendLine(
                $"{indent}            __var_{info.BoundVarNames[i]} = egraph.union_find.find({childExpr});");
        }

        sb.AppendLine($"{indent}            return true;");
        sb.AppendLine($"{indent}        }}");
        sb.AppendLine($"{indent}    }}");
        sb.AppendLine($"{indent}    return false;");
        sb.AppendLine($"{indent}}}");
    }

