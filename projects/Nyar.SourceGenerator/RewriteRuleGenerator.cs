    /// <summary>
    ///     生成工厂 partial class，提供静态方法返回所有生成的规则实例
    /// </summary>
    private static void GenerateFactoryClass(
        GeneratorExecutionContext context,
        RulePairInfo first,
        string safeClassName,
        List<string> ruleClassNames)
    {
        var factorySb = new StringBuilder();
        factorySb.AppendLine("// <auto-generated/>");
        factorySb.AppendLine("#pragma warning disable CS0105");
        factorySb.AppendLine("using System.Collections.Generic;");
        factorySb.AppendLine("using Nyar.IR.Intent;");
        factorySb.AppendLine("using Nyar.IR.Rewrite;");
        factorySb.AppendLine("#pragma warning restore CS0105");
        factorySb.AppendLine();

        var ns = first.Namespace;
        if (string.IsNullOrEmpty(ns))
        {
            factorySb.AppendLine("// 命名空间为空，无法生成工厂 partial class");
            return;
        }

        factorySb.AppendLine($"namespace {ns};");
        factorySb.AppendLine();

        var typeName = first.ContainingTypeName;
        factorySb.AppendLine("/// <summary>");
        factorySb.AppendLine($"///     {typeName} 的生成工厂方法，提供所有由 Source Generator 生成的重写规则实例");
        factorySb.AppendLine("/// </summary>");
        factorySb.AppendLine($"{GeneratedCodeAttr}");
        factorySb.AppendLine($"public static partial class {typeName}");
        factorySb.AppendLine("{");
        factorySb.AppendLine("    /// <summary>");
        factorySb.AppendLine("    ///     获取所有由 [RewriteRule] 属性生成的 IRewriteRule&lt;Oa&gt; 实现类");
        factorySb.AppendLine("    /// </summary>");
        factorySb.AppendLine("    /// <returns>生成的重写规则列表。</returns>");
        factorySb.AppendLine("    public static IReadOnlyList<IRewriteRule<Oa>> GeneratedRules()");
        factorySb.AppendLine("    {");
        factorySb.AppendLine("        return new List<IRewriteRule<Oa>>");
        factorySb.AppendLine("        {");

        for (var i = 0; i < ruleClassNames.Count; i++)
        {
            var sep = i < ruleClassNames.Count - 1 ? "," : "";
            factorySb.AppendLine($"            new {ruleClassNames[i]}(){sep}");
        }

        factorySb.AppendLine("        };");
        factorySb.AppendLine("    }");
        factorySb.AppendLine("}");

        context.AddSource($"Generated_{safeClassName}_Factory.g.cs",
            SourceText.From(factorySb.ToString(), Encoding.UTF8));
    }

