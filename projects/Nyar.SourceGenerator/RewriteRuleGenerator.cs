    /// <summary>
    ///     生成单个重写规则类
    /// </summary>
    private void GenerateRuleClass(StringBuilder sb, RulePairInfo rule, string indent)
    {
        var className = $"Generated_{SanitizeIdentifier(rule.RuleName)}_Rule";
        var safeRuleName = EscapeCSharpString(rule.RuleName);

        // 收集嵌套模式，用于生成匹配辅助方法
        var nestedPatterns = CollectNestedPatterns(rule.PatternTree);

        sb.AppendLine($"{indent}/// <summary>");
        sb.AppendLine($"{indent}///     重写规则：{safeRuleName}");
        sb.AppendLine($"{indent}/// </summary>");
        sb.AppendLine($"{indent}{GeneratedCodeAttr}");
        sb.AppendLine($"{indent}internal sealed class {className} : IRewriteRule<Oa>");
        sb.AppendLine($"{indent}{{");

        // 属性
        sb.AppendLine($"{indent}    /// <summary>");
        sb.AppendLine($"{indent}    ///     规则名称");
        sb.AppendLine($"{indent}    /// </summary>");
        sb.AppendLine($"{indent}    public string name => \"{safeRuleName}\";");
        sb.AppendLine();
        sb.AppendLine($"{indent}    /// <summary>");
        sb.AppendLine($"{indent}    ///     规则代价（默认 1）");
        sb.AppendLine($"{indent}    /// </summary>");
        sb.AppendLine($"{indent}    public int Cost => 1;");
        sb.AppendLine();

        // Matches 方法
        GenerateMatchesMethod(sb, rule, nestedPatterns, indent + "    ");
        sb.AppendLine();

        // PatternAndReplacement 方法
        GenerateBuildPairMethod(sb, rule, nestedPatterns, indent + "    ");
        sb.AppendLine();

        // 嵌套模式匹配辅助方法
        foreach (var nested in nestedPatterns)
        {
            GenerateNestedMatchHelper(sb, nested, indent + "    ");
            sb.AppendLine();
        }

        // Apply 方法（接口实现）
        sb.AppendLine($"{indent}    /// <summary>");
        sb.AppendLine($"{indent}    ///     对 E-Graph 应用此重写规则，遍历所有等价类并合并匹配到的等价关系");
        sb.AppendLine($"{indent}    /// </summary>");
        sb.AppendLine($"{indent}    /// <param name=\"egraph\">目标 E-Graph。</param>");
        sb.AppendLine($"{indent}    /// <returns>是否产生了新的等价关系。</returns>");
        sb.AppendLine($"{indent}    public bool apply(EGraph<Oa> egraph)");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        var changed = false;");
        sb.AppendLine($"{indent}        var classIds = egraph.classes.Keys.ToList();");
        sb.AppendLine();
        sb.AppendLine($"{indent}        foreach (var classId in classIds)");
        sb.AppendLine($"{indent}        {{");
        sb.AppendLine($"{indent}            var id = new Id(classId);");
        sb.AppendLine($"{indent}            if (egraph.get_class(id) is null) continue;");
        sb.AppendLine();
        sb.AppendLine($"{indent}            var match = Matches(egraph, id);");
        sb.AppendLine($"{indent}            if (match is null) continue;");
        sb.AppendLine();
        sb.AppendLine($"{indent}            var (pattern, replacement) = BuildPatternAndReplacement(egraph, match);");
        sb.AppendLine($"{indent}            if (replacement is null) continue;");
        sb.AppendLine();
        sb.AppendLine($"{indent}            var patternId = egraph.add(pattern);");
        sb.AppendLine($"{indent}            var replacementId = egraph.add(replacement);");
        sb.AppendLine($"{indent}            var root1 = egraph.union_find.find(patternId);");
        sb.AppendLine($"{indent}            var root2 = egraph.union_find.find(replacementId);");
        sb.AppendLine($"{indent}            if (root1 != root2)");
        sb.AppendLine($"{indent}            {{");
        sb.AppendLine($"{indent}                egraph.union(patternId, replacementId);");
        sb.AppendLine($"{indent}                changed = true;");
        sb.AppendLine($"{indent}            }}");
        sb.AppendLine($"{indent}        }}");
        sb.AppendLine();
        sb.AppendLine($"{indent}        if (changed)");
        sb.AppendLine($"{indent}        {{");
        sb.AppendLine($"{indent}            egraph.rebuild();");
        sb.AppendLine($"{indent}        }}");
        sb.AppendLine();
        sb.AppendLine($"{indent}        return changed;");
        sb.AppendLine($"{indent}    }}");

        sb.AppendLine($"{indent}}}");
    }

    /// <summary>
    ///     生成 Matches 方法：基于模式表达式匹配指定等价类
    /// </summary>
    private void GenerateMatchesMethod(StringBuilder sb, RulePairInfo rule, List<NestedPatternInfo> nestedPatterns,
        string indent)
    {
        var patternTree = rule.PatternTree;
        var allVars = CollectVarNames(patternTree);

        // 构建变量名到嵌套辅助方法的映射
        var nestedHelperMap = new Dictionary<string, NestedPatternInfo>(StringComparer.Ordinal);
        foreach (var np in nestedPatterns)
        {
            var key = string.Join(",", np.BoundVarNames.OrderBy(v => v, StringComparer.Ordinal));
            nestedHelperMap[key] = np;
        }

        sb.AppendLine($"{indent}/// <summary>");
        sb.AppendLine($"{indent}///     尝试将指定等价类匹配为此规则的模式，返回变量绑定结果");
        sb.AppendLine($"{indent}/// </summary>");
        sb.AppendLine($"{indent}/// <param name=\"egraph\">目标 E-Graph。</param>");
        sb.AppendLine($"{indent}/// <param name=\"id\">等价类标识符。</param>");
        sb.AppendLine($"{indent}/// <returns>匹配成功返回变量绑定；否则返回 null。</returns>");
        sb.AppendLine($"{indent}public MatchResult? Matches(EGraph<Oa> egraph, Id id)");
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    var nodes = egraph.get_nodes(id);");
        sb.AppendLine($"{indent}    if (nodes.Count == 0) return null;");
        sb.AppendLine();

        var hasVars = allVars.Count > 0;

        if (!hasVars)
        {
            // 无变量：检查是否有节点匹配模式（始终需要 var 来解构属性）
            sb.AppendLine($"{indent}    foreach (var node in nodes)");
            sb.AppendLine($"{indent}    {{");
            EmitMatchCheck(sb, patternTree, indent + "        ", "node", true);
            sb.AppendLine($"{indent}        return MatchResult.Empty;");
            EmitCloseIfNeeded(sb, patternTree, indent + "        ");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    return null;");
        }
        else
        {
            // 有变量：检查并捕获变量绑定
            var varList = allVars.ToList();
            varList.Sort(StringComparer.Ordinal);

            sb.AppendLine($"{indent}    foreach (var node in nodes)");
            sb.AppendLine($"{indent}    {{");
            foreach (var v in varList) sb.AppendLine($"{indent}        Id __var_{v} = default;");
            sb.AppendLine();

            var matched =
                EmitMatchCheckWithVars(sb, patternTree, indent + "        ", "node", allVars, nestedHelperMap);

            if (matched)
            {
                var dictEntries = string.Join(", ",
                    varList.Select(v => $"{{ \"{EscapeCSharpString(v)}\", __var_{v} }}"));
                sb.AppendLine(
                    $"{indent}        return new MatchResult(new Dictionary<string, Id> {{ {dictEntries} }});");
                EmitCloseIfNeededForVarMatch(sb, patternTree, indent + "        ");
            }

            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    return null;");
        }

        sb.AppendLine($"{indent}}}");
    }

    /// <summary>
    ///     生成无变量模式匹配检查（直接返回 bool 效果）
    /// </summary>
    private void EmitMatchCheck(StringBuilder sb, PatternNode node, string indent, string nodeExpr,
        bool hasLetBinding)
    {
        if (node.IsInfixSemantic && node.Children.Count == 2)
        {
            var left = node.Children[0];
            var right = node.Children[1];
            var varPrefix = hasLetBinding ? "var " : "";

            var oaPattern = GetCoreInfixMatchPattern(node.OperatorString!, "__l", "__r", hasLetBinding);
            if (oaPattern is not null)
                sb.Append($"{indent}if ({nodeExpr} is {oaPattern}");
            else
                sb.Append($"{indent}if (false");

            var additionalChecks = new List<string>();
            if (!left.IsVarReference && !left.IsLeaf) additionalChecks.Add(GenerateChildCheck("__l", left));

            if (!right.IsVarReference && !right.IsLeaf) additionalChecks.Add(GenerateChildCheck("__r", right));

            if (additionalChecks.Count > 0) sb.Append($" && {string.Join(" && ", additionalChecks)}");

            sb.AppendLine(")");
            sb.AppendLine($"{indent}{{");
        }
        else if (node.IsPrefixSemantic && node.Children.Count == 1)
        {
            var operand = node.Children[0];
            var varPrefix = hasLetBinding ? "var " : "";

            var oaPattern = GetCorePrefixMatchPattern(node.OperatorString!, "__op", hasLetBinding);
            if (oaPattern is not null)
                sb.Append($"{indent}if ({nodeExpr} is {oaPattern}");
            else
                sb.Append($"{indent}if (false");

            if (!operand.IsVarReference && !operand.IsLeaf) sb.Append($" && {GenerateChildCheck("__op", operand)}");

            sb.AppendLine(")");
            sb.AppendLine($"{indent}{{");
        }
        else if (node.IsLiteral)
        {
            sb.AppendLine($"{indent}if ({nodeExpr} is {node.LiteralNodeType})");
            sb.AppendLine($"{indent}{{");
        }
        else if (node.IsVarReference)
        {
            sb.AppendLine($"{indent}// var: {node.VarName}");
        }
        else
        {
            sb.AppendLine(
                $"{indent}if ({nodeExpr} is StrategyNode.Extension {{ Name: \"{EscapeCSharpString(node.OperationName)}\" }})");
            sb.AppendLine($"{indent}{{");
        }
    }

    /// <summary>
    ///     生成带变量捕获的模式匹配检查
    /// </summary>
    /// <returns>是否成功匹配</returns>
    private bool EmitMatchCheckWithVars(StringBuilder sb, PatternNode node, string indent, string nodeExpr,
        HashSet<string> allVars, Dictionary<string, NestedPatternInfo> nestedHelperMap)
    {
        if (node.IsInfixSemantic && node.Children.Count == 2)
        {
            var left = node.Children[0];
            var right = node.Children[1];
            var bindingStmts = new List<string>();

            var oaPattern = GetCoreInfixMatchPattern(node.OperatorString!, "__l", "__r", true);
            if (oaPattern is not null)
            {
                sb.Append($"{indent}if ({nodeExpr} is {oaPattern}");
            }
            else
            {
                sb.Append($"{indent}if (false");
            }

            var conditions = new List<string>();

            if (left.IsVarReference)
            {
                conditions.Add(
                    $"TryGetVar(egraph, __l, \"{EscapeCSharpString(left.VarName!)}\", ref __var_{left.VarName})");
            }
            else if (!left.IsLeaf)
            {
                var leftHelperCall = GenerateNestedHelperCall("__l", left, nestedHelperMap);
                if (leftHelperCall is not null)
                    conditions.Add(leftHelperCall);
                else
                    conditions.Add(GenerateChildCheck("__l", left));

                CollectLiteralVarBindings(left, "__l", bindingStmts);
            }

            if (right.IsVarReference)
            {
                conditions.Add(
                    $"TryGetVar(egraph, __r, \"{EscapeCSharpString(right.VarName!)}\", ref __var_{right.VarName})");
            }
            else if (!right.IsLeaf)
            {
                var rightHelperCall = GenerateNestedHelperCall("__r", right, nestedHelperMap);
                if (rightHelperCall is not null)
                    conditions.Add(rightHelperCall);
                else
                    conditions.Add(GenerateChildCheck("__r", right));

                CollectLiteralVarBindings(right, "__r", bindingStmts);
            }

            foreach (var check in conditions) sb.Append($" && {check}");

            sb.AppendLine(")");
            sb.AppendLine($"{indent}{{");
            EmitBindingStatements(sb, bindingStmts, indent + "    ");
            return true;
        }

        if (node.IsPrefixSemantic && node.Children.Count == 1)
        {
            var operand = node.Children[0];
            var bindingStmts = new List<string>();

            var oaPattern = GetCorePrefixMatchPattern(node.OperatorString!, "__op", true);
            if (oaPattern is not null)
                sb.Append($"{indent}if ({nodeExpr} is {oaPattern}");
            else
                sb.Append($"{indent}if (false");

            if (operand.IsVarReference)
            {
                sb.Append(
                    $" && TryGetVar(egraph, __op, \"{EscapeCSharpString(operand.VarName!)}\", ref __var_{operand.VarName})");
            }
            else if (!operand.IsLeaf)
            {
                sb.Append($" && {GenerateChildCheck("__op", operand)}");
                CollectLiteralVarBindings(operand, "__op", bindingStmts);
            }

            sb.AppendLine(")");
            sb.AppendLine($"{indent}{{");
            EmitBindingStatements(sb, bindingStmts, indent + "    ");
            return true;
        }

        if (node.IsLiteral)
        {
            // 根模式为字面量：匹配等价类中的节点，变量绑定到该等价类 Id
            sb.AppendLine($"{indent}if ({nodeExpr} is {node.LiteralNodeType})");
            sb.AppendLine($"{indent}{{");

            if (node.Children.Count == 1 && node.Children[0].IsVarReference)
            {
                var varName = node.Children[0].VarName!;
                sb.AppendLine($"{indent}    __var_{varName} = egraph.union_find.find(id);");
            }

            return true;
        }

        if (node.IsVarReference)
        {
            sb.AppendLine(
                $"{indent}if (TryGetVar(egraph, id, \"{EscapeCSharpString(node.VarName!)}\", ref __var_{node.VarName}))");
            sb.AppendLine($"{indent}{{");
            return true;
        }

        // 自定义操作
        sb.Append(
            $"{indent}if ({nodeExpr} is StrategyNode.Extension {{ Name: \"{EscapeCSharpString(node.OperationName)}\", Children: var __children }})");
        sb.AppendLine();
        sb.AppendLine($"{indent}{{");

        // 提取自定义操作的子节点变量
        for (var i = 0; i < node.Children.Count; i++)
        {
            var child = node.Children[i];
            if (child.IsVarReference)
            {
                sb.AppendLine($"{indent}    if (__children.Length > {i})");
                sb.AppendLine(
                    $"{indent}        __var_{child.VarName} = egraph.union_find.find(__children[{i}]);");
            }
            else if (child.IsLiteral && child.Children.Any(c => c.IsVarReference))
            {
                // 字面量子节点：检查类型后绑定变量到子节点 Id
                sb.AppendLine($"{indent}    if (__children.Length > {i})");
                sb.AppendLine($"{indent}    {{");
                sb.AppendLine(
                    $"{indent}        var __childId = egraph.union_find.find(__children[{i}]);");
                sb.AppendLine(
                    $"{indent}        if ({GenerateChildCheck("__childId", child)})");
                sb.AppendLine($"{indent}        {{");
                foreach (var c in child.Children)
                    if (c.IsVarReference)
                        sb.AppendLine(
                            $"{indent}            __var_{c.VarName} = __childId;");

                sb.AppendLine($"{indent}        }}");
                sb.AppendLine($"{indent}    }}");
            }
        }

        return true;
    }

    /// <summary>
    ///     收集字面量中包含的变量，生成绑定语句（将变量绑定到子节点 Id）
    /// </summary>
    private static void CollectLiteralVarBindings(PatternNode node, string childIdExpr, List<string> bindingStmts)
    {
        if (node.IsLiteral)
        {
            foreach (var child in node.Children)
                if (child.IsVarReference)
                    bindingStmts.Add(
                        $"__var_{child.VarName} = egraph.union_find.find({childIdExpr});");
        }
        else if (node.IsInfixSemantic || node.IsPrefixSemantic)
        {
            // 嵌套的二元/一元运算：变量捕获不在此层处理，
            // 通过 GenerateChildCheck 利用 ChildMatchesBinaryOp/ChildMatchesUnaryOp 在 e-class 级别检查
        }
    }

    /// <summary>
    ///     输出变量绑定语句
    /// </summary>
    private static void EmitBindingStatements(StringBuilder sb, List<string> bindingStmts, string indent)
    {
        foreach (var stmt in bindingStmts) sb.AppendLine($"{indent}{stmt};");
    }

    /// <summary>
    ///     关闭 EmitMatchCheck 的 if 块
    /// </summary>
    private static void EmitCloseIfNeeded(StringBuilder sb, PatternNode node, string indent)
    {
        // 仅对生成 if 块的节点类型关闭
        if (node.IsInfixSemantic || node.IsPrefixSemantic || node.IsLiteral || node.OperationName != "unknown")
            sb.AppendLine($"{indent}    }}");
    }

    /// <summary>
    ///     关闭带变量的匹配检查的 if 块
    /// </summary>
    private void EmitCloseIfNeededForVarMatch(StringBuilder sb, PatternNode node, string indent)
    {
        sb.AppendLine($"{indent}    }}");
    }

    /// <summary>
    ///     生成子节点类型匹配检查表达式
    /// </summary>
    private static string GenerateChildCheck(string childIdExpr, PatternNode child)
    {
        if (child.IsLiteral)
            return $"ChildMatchesNodeType(egraph, {childIdExpr}, \"{EscapeCSharpString(child.LiteralNodeType!)}\")";

        if (child.IsInfixSemantic)
            return
                $"ChildMatchesInfixSemantic(egraph, {childIdExpr}, \"{EscapeCSharpString(child.OperatorString!)}\")";

        if (child.IsPrefixSemantic)
            return
                $"ChildMatchesPrefixSemantic(egraph, {childIdExpr}, \"{EscapeCSharpString(child.OperatorString!)}\")";

        // 自定义操作
        return
            $"ChildMatchesExtension(egraph, {childIdExpr}, \"{EscapeCSharpString(child.OperationName)}\")";
    }

    /// <summary>
    ///     为嵌套非叶子子模式生成辅助方法调用表达式
    /// </summary>
    /// <param name="childIdExpr">子等价类 Id 表达式。</param>
    /// <param name="child">子模式节点。</param>
    /// <param name="nestedHelperMap">嵌套模式到辅助方法的映射。</param>
    /// <returns>辅助方法调用表达式；若无匹配项则返回 null。</returns>
    private static string? GenerateNestedHelperCall(string childIdExpr, PatternNode child,
        Dictionary<string, NestedPatternInfo> nestedHelperMap)
    {
        if (!child.IsInfixSemantic && !child.IsPrefixSemantic) return null;

        var directVars = child.GetDirectVarNames();
        if (directVars.Count == 0) return null;

        var key = string.Join(",", directVars.OrderBy(v => v, StringComparer.Ordinal));
        if (!nestedHelperMap.TryGetValue(key, out var info)) return null;

        var refArgs = string.Join(", ",
            directVars.Select(v => $"ref __var_{v}"));
        return $"{info.HelperMethodName}(egraph, {childIdExpr}, {refArgs})";
    }

    /// <summary>
    ///     生成 BuildPatternAndReplacement 方法
    /// </summary>
    private void GenerateBuildPairMethod(StringBuilder sb, RulePairInfo rule, List<NestedPatternInfo> nestedPatterns,
        string indent)
    {
        var patternTree = rule.PatternTree;
        var allVars = CollectVarNames(patternTree);
        var varList = allVars.ToList();
        varList.Sort(StringComparer.Ordinal);

        sb.AppendLine($"{indent}/// <summary>");
        sb.AppendLine($"{indent}///     根据匹配结果构建模式和替换节点对");
        sb.AppendLine($"{indent}/// </summary>");
        sb.AppendLine($"{indent}/// <param name=\"egraph\">目标 E-Graph。</param>");
        sb.AppendLine($"{indent}/// <param name=\"match\">匹配结果。</param>");
        sb.AppendLine($"{indent}/// <returns>(模式节点, 替换节点) 元组；若守卫检查失败则替换为 null。</returns>");
        sb.AppendLine(
            $"{indent}private (Oa Pattern, Oa? Replacement) BuildPatternAndReplacement(EGraph<Oa> egraph, MatchResult match)");
        sb.AppendLine($"{indent}{{");

        // 提取变量
        foreach (var varName in varList)
            sb.AppendLine(
                $"{indent}    var __var_{varName} = match[\"{EscapeCSharpString(varName)}\"];");

        sb.AppendLine();

        // 构建模式节点 — 对嵌套模式使用 egraph.add() 获取内层 Id
        var hasNesting = nestedPatterns.Count > 0;
        if (hasNesting)
        {
            // 嵌套模式：先生成内层节点的 Id，再构建外层 Oa
            var patCounter = new[] { 0 };
            var patternExpr = EmitNestedPatternConstruction(sb, patternTree, indent + "    ", ref patCounter, true);
            sb.AppendLine($"{indent}    var __pattern = {patternExpr};");
        }
        else
        {
            var patternExpr = GenerateFlatPatternExpression(patternTree);
            sb.AppendLine($"{indent}    var __pattern = {patternExpr};");
        }

        sb.AppendLine();

        // 守卫检查
        if (rule.GuardMethodName is not null)
        {
            var guardArgs = string.Join(", ", varList.Select(v => $"__var_{v}"));
            sb.AppendLine(
                $"{indent}    if (!{rule.ContainingTypeName}.{rule.GuardMethodName}(egraph, {guardArgs}))");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        return (__pattern, null);");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine();
        }

        // 构建替换节点（调用静态替换方法）
        if (varList.Count == 0)
        {
            sb.AppendLine(
                $"{indent}    var __replacement = {rule.ContainingTypeName}.{rule.ReplacementMethodName}(egraph);");
        }
        else
        {
            var replacementArgs = string.Join(", ", varList.Select(v => $"__var_{v}"));
            sb.AppendLine(
                $"{indent}    var __replacement = {rule.ContainingTypeName}.{rule.ReplacementMethodName}(egraph, {replacementArgs});");
        }

        sb.AppendLine($"{indent}    return (__pattern, __replacement);");
        sb.AppendLine($"{indent}}}");

        // 生成辅助方法
        GenerateHelperMethods(sb, indent);
    }

    /// <summary>
    ///     为嵌套模式构造生成代码：从变量绑定构建内层 Oa 节点并返回内层 Id 表达式。
    ///     同时向 sb 输出生成子节点的语句。
    /// </summary>
    /// <param name="isRoot">是否处理根节点（根节点返回 Oa 表达式；子节点返回 Id）。</param>
    private static string EmitNestedPatternConstruction(StringBuilder sb, PatternNode node, string indent,
        ref int[] counter, bool isRoot = false)
    {
        if (node.IsVarReference) return $"__var_{node.VarName}";

        if (node.IsInfixSemantic && node.Children.Count == 2)
        {
            var left = node.Children[0];
            var right = node.Children[1];

            var leftExpr = EmitNestedPatternConstruction(sb, left, indent, ref counter);
            var rightExpr = EmitNestedPatternConstruction(sb, right, indent, ref counter);

            var nodeExpr = BuildOaBinaryOp(node.OperatorString!, leftExpr, rightExpr);

            if (isRoot) return nodeExpr;

            var tmpId = $"__pat_{counter[0]++}";
            sb.AppendLine($"{indent}var {tmpId} = egraph.add({nodeExpr});");
            return tmpId;
        }

        if (node.IsPrefixSemantic && node.Children.Count == 1)
        {
            var operandExpr = EmitNestedPatternConstruction(sb, node.Children[0], indent, ref counter);
            var nodeExpr = BuildOaUnaryOp(node.OperatorString!, operandExpr);

            if (isRoot) return nodeExpr;

            var tmpId = $"__pat_{counter[0]++}";
            sb.AppendLine($"{indent}var {tmpId} = egraph.add({nodeExpr});");
            return tmpId;
        }

        return "new Nyar.Dialect.Sonic.Core.Nodes.Literal<object?>(null)";
    }

    /// <summary>
    ///     为模式构造获取子节点表达式：变量引用直接用 Id，嵌套节点先 add 再返回 Id
    /// </summary>
    private static string GetChildExprForConstruction(StringBuilder sb, PatternNode child, string indent,
        ref int[] counter)
    {
        if (child.IsVarReference) return $"__var_{child.VarName}";

        if (child.IsInfixSemantic && child.Children.Count == 2)
        {
            var leftExpr = GetChildExprForConstruction(sb, child.Children[0], indent, ref counter);
            var rightExpr = GetChildExprForConstruction(sb, child.Children[1], indent, ref counter);
            var nodeExpr = BuildOaBinaryOp(child.OperatorString!, leftExpr, rightExpr);
            var tmpId = $"__pat_{counter[0]++}";
            sb.AppendLine($"{indent}var {tmpId} = egraph.add({nodeExpr});");
            return tmpId;
        }

        if (child.IsPrefixSemantic && child.Children.Count == 1)
        {
            var operandExpr = GetChildExprForConstruction(sb, child.Children[0], indent, ref counter);
            var nodeExpr = BuildOaUnaryOp(child.OperatorString!, operandExpr);
            var tmpId = $"__pat_{counter[0]++}";
            sb.AppendLine($"{indent}var {tmpId} = egraph.add({nodeExpr});");
            return tmpId;
        }

        return "new Nyar.Dialect.Sonic.Core.Nodes.Literal<object?>(null)";
    }

    /// <summary>
    ///     生成扁平模式表达式（仅用于无嵌套子模式的简单规则）
    /// </summary>
    private static string GenerateFlatPatternExpression(PatternNode node)
    {
        if (node.IsVarReference) return $"__var_{node.VarName}";

        if (node.IsInfixSemantic && node.Children.Count == 2)
        {
            var left = GenerateFlatPatternExpression(node.Children[0]);
            var right = GenerateFlatPatternExpression(node.Children[1]);
            return BuildOaBinaryOp(node.OperatorString!, left, right);
        }

        if (node.IsPrefixSemantic && node.Children.Count == 1)
        {
            var operand = GenerateFlatPatternExpression(node.Children[0]);
            return BuildOaUnaryOp(node.OperatorString!, operand);
        }

        if (node.IsLiteral)
        {
            if (node.Children.Count == 1 && node.Children[0].IsVarReference)
            {
                var varName = node.Children[0].VarName;
                return $"__var_{varName}";
            }

            return "new Nyar.Dialect.Sonic.Core.Nodes.Literal<long>(0)";
        }

        if (node.Children.Count > 0)
        {
            var children = string.Join(", ",
                node.Children.Select(c => GenerateFlatPatternExpression(c)));
            return $"new StrategyNode.Extension(\"{EscapeCSharpString(node.OperationName)}\", [{children}])";
        }

        return
            $"new StrategyNode.Extension(\"{EscapeCSharpString(node.OperationName)}\", ImmutableArray<Id>.Empty)";
    }

    /// <summary>
    ///     根据二元运算符字符串构建 OA 节点构造表达式
    /// </summary>
    private static string BuildOaBinaryOp(string op, string leftExpr, string rightExpr)
    {
        return op switch
        {
            "add" => $"new Nyar.Dialect.Sonic.Core.Nodes.Add({leftExpr}, {rightExpr})",
            "sub" => $"new Nyar.Dialect.Sonic.Core.Nodes.Sub({leftExpr}, {rightExpr})",
            "mul" => $"new Nyar.Dialect.Sonic.Core.Nodes.Mul({leftExpr}, {rightExpr})",
            "div" => $"new Nyar.Dialect.Sonic.Core.Nodes.Div({leftExpr}, {rightExpr})",
            "and" => $"new Nyar.Dialect.Sonic.Core.Nodes.And({leftExpr}, {rightExpr})",
            "or" => $"new Nyar.Dialect.Sonic.Core.Nodes.Or({leftExpr}, {rightExpr})",
            "eq" => $"new Nyar.Dialect.Sonic.Core.Nodes.Cmp(CompareOp.eq, {leftExpr}, {rightExpr})",
            "ne" => $"new Nyar.Dialect.Sonic.Core.Nodes.Cmp(CompareOp.ne, {leftExpr}, {rightExpr})",
            "lt" => $"new Nyar.Dialect.Sonic.Core.Nodes.Cmp(CompareOp.lt, {leftExpr}, {rightExpr})",
            "le" => $"new Nyar.Dialect.Sonic.Core.Nodes.Cmp(CompareOp.le, {leftExpr}, {rightExpr})",
            "gt" => $"new Nyar.Dialect.Sonic.Core.Nodes.Cmp(CompareOp.gt, {leftExpr}, {rightExpr})",
            "ge" => $"new Nyar.Dialect.Sonic.Core.Nodes.Cmp(CompareOp.ge, {leftExpr}, {rightExpr})",
            _ => $"throw new global::System.NotSupportedException($\"不支持的二元运算符: {{({op})}}\")"
        };
    }

    /// <summary>
    ///     根据一元运算符字符串构建 OA 节点构造表达式
    /// </summary>
    private static string BuildOaUnaryOp(string op, string operandExpr)
    {
        return op switch
        {
            "neg" => $"new Nyar.Dialect.Sonic.Core.Nodes.Neg({operandExpr})",
            "not" => $"new Nyar.Dialect.Sonic.Core.Nodes.Not({operandExpr})",
            _ => $"throw new global::System.NotSupportedException($\"不支持的一元运算符: {{({op})}}\")"
        };
    }

    /// <summary>
