        sb.AppendLine($"{indent}        \"ne\" => childNodes.Any(n => n is Cmp {{ op: CompareOp.ne }}),");
        sb.AppendLine($"{indent}        \"lt\" => childNodes.Any(n => n is Cmp {{ op: CompareOp.lt }}),");
