    #region 模式分析

    /// <summary>
    ///     模式表达式语法树节点
    /// </summary>
    private sealed class PatternNode
    {
        /// <summary>操作名（方法名，如 Add/Int32）</summary>
        public string OperationName { get; set; } = string.Empty;

        /// <summary>子节点列表</summary>
        public List<PatternNode> Children { get; set; } = [];

        /// <summary>变量名（若此节点为 Var&lt;T&gt; 引用）</summary>
        public string? VarName { get; set; }

        /// <summary>是否为 Var&lt;T&gt; 变量引用</summary>
        public bool IsVarReference => VarName is not null;

        /// <summary>是否为叶子节点（无子节点且非变量）</summary>
        public bool IsLeaf => Children.Count == 0 && !IsVarReference;

        /// <summary>是否为二元运算</summary>
        public bool IsInfixSemantic { get; set; }

        /// <summary>是否为一元运算</summary>
        public bool IsPrefixSemantic { get; set; }

        /// <summary>是否为字面量构造（Int32/Float32 等）</summary>
        public bool IsLiteral { get; set; }

        /// <summary>Oa 运算符字符串（如 add/sub）</summary>
        public string? OperatorString { get; set; }

        /// <summary>字面量对应的 Oa 节点类型名</summary>
        public string? LiteralNodeType { get; set; }

        /// <summary>
        ///     获取此节点及其所有子节点中直接绑定的变量名列表（仅直接 VarReference children）
        /// </summary>
        public List<string> GetDirectVarNames()
        {
            var vars = new List<string>();
            foreach (var child in Children)
                if (child.IsVarReference)
                    vars.Add(child.VarName!);

            return vars;
        }
    }

    /// <summary>
    ///     嵌套模式匹配信息，用于生成匹配内层运算语义的辅助方法
    /// </summary>
    private sealed class NestedPatternInfo
    {
        /// <summary>运算符字符串（如 add/sub）</summary>
        public string OperatorString { get; set; } = string.Empty;

        /// <summary>是否是二元运算</summary>
        public bool IsInfixSemantic { get; set; } = true;

        /// <summary>要绑定的变量名列表（按子节点顺序）</summary>
        public List<string> BoundVarNames { get; set; } = [];

        /// <summary>生成的辅助方法名</summary>
        public string HelperMethodName =>
            IsInfixSemantic
                ? $"MatchInfixSemantic_{OperatorString}_{string.Join("_", BoundVarNames)}"
                : $"MatchPrefixSemantic_{OperatorString}_{string.Join("_", BoundVarNames)}";
    }

    /// <summary>
    ///     分析模式方法体，提取模式表达式树
    /// </summary>
    private PatternNode? AnalyzePatternMethod(MethodWithAttributes ruleMethod)
    {
        var syntax = ruleMethod.Syntax;
        ExpressionSyntax? body = null;

        if (syntax.ExpressionBody is not null)
        {
            body = syntax.ExpressionBody.Expression;
        }
        else
        {
            var returnStmt = syntax.Body?.Statements
                .OfType<ReturnStatementSyntax>().FirstOrDefault();
            if (returnStmt != null) body = returnStmt.Expression;
        }

        if (body is null) return null;

        // 识别方法参数中的 Var<T> 类型
        var varParams = new HashSet<string>(StringComparer.Ordinal);
        foreach (var param in syntax.ParameterList.Parameters)
        {
            var typeName = param.Type?.ToString() ?? string.Empty;
            if (typeName.StartsWith("Var<") || typeName.StartsWith("Nyar.IR.Rewrite.Var<"))
                varParams.Add(param.Identifier.Text);
        }

        return AnalyzeExpression(body, varParams);
    }

    /// <summary>
    ///     递归分析表达式，构建模式树
    /// </summary>
    private PatternNode? AnalyzeExpression(ExpressionSyntax expr, HashSet<string> varParams)
    {
        switch (expr)
        {
            case InvocationExpressionSyntax invocation:
                return AnalyzeInvocation(invocation, varParams);

            case IdentifierNameSyntax identifier:
            {
                var name = identifier.Identifier.Text;
                if (varParams.Contains(name)) return new PatternNode { VarName = name };

                return null;
            }

            case LiteralExpressionSyntax literal:
                return new PatternNode
                {
                    OperationName = "literal",
                    OperatorString = literal.Token.ValueText
                };

            case BinaryExpressionSyntax binaryExpr:
                return AnalyzeBinaryExpression(binaryExpr, varParams);

            case PrefixUnaryExpressionSyntax prefixUnary:
                return AnalyzeUnaryExpression(prefixUnary, varParams);

            case ParenthesizedExpressionSyntax parens:
                return AnalyzeExpression(parens.Expression, varParams);

            case MemberAccessExpressionSyntax memberAccess:
            {
                // 处理 using static 场景：a.Int32(x) 压缩为 Int32(x)
                var simpleName = memberAccess.Name.Identifier.Text;
                if (LiteralNodeType.ContainsKey(simpleName))
                    return AnalyzeSimpleInvocation(simpleName, memberAccess, varParams);

                return null;
            }

            default:
                return null;
        }
    }

    /// <summary>
    ///     分析方法调用表达式（如 a.Add(a.Int32(x), y)）
    /// </summary>
    private PatternNode? AnalyzeInvocation(InvocationExpressionSyntax invocation, HashSet<string> varParams)
    {
        var methodName = GetMethodName(invocation);
        if (methodName is null) return null;

        // 检查是否为已知字面量构造
        if (LiteralNodeType.TryGetValue(methodName, out var literalType))
        {
            var node = new PatternNode
            {
                OperationName = methodName,
                IsLiteral = true,
                LiteralNodeType = literalType
            };

            // 字面量可能有 Var<T> 参数作为值
            foreach (var arg in invocation.ArgumentList.Arguments)
            {
                var child = AnalyzeExpression(arg.Expression, varParams);
                if (child is not null) node.Children.Add(child);
            }

            return node;
        }

        // 检查是否为已知二元运算
        var args = invocation.ArgumentList.Arguments;
        if (InfixOperatorMethodMap.TryGetValue(methodName, out var binaryOp))
        {
            // 支持两种调用风格：
            // 1. 旧风格：Add(left, right) — 两个参数
            // 2. 流畅风格：x.Add(y) — 一个参数，左操作数为接收者
            if (args.Count == 2)
            {
                var left = AnalyzeExpression(args[0].Expression, varParams);
                var right = AnalyzeExpression(args[1].Expression, varParams);

                if (left is null || right is null) return null;

                return new PatternNode
                {
                    OperationName = methodName,
                    IsInfixSemantic = true,
                    OperatorString = binaryOp,
                    Children = [left, right]
                };
            }

            if (args.Count == 1 && invocation.Expression is MemberAccessExpressionSyntax memberAccess)
            {
                var left = AnalyzeExpression(memberAccess.Expression, varParams);
                var right = AnalyzeExpression(args[0].Expression, varParams);

                if (left is null || right is null) return null;

                return new PatternNode
                {
                    OperationName = methodName,
                    IsInfixSemantic = true,
                    OperatorString = binaryOp,
                    Children = [left, right]
                };
            }

            return null;
        }

        // 检查是否为已知一元运算
        if (PrefixOperatorMethodMap.TryGetValue(methodName, out var unaryOp))
        {
            if (args.Count != 1) return null;

            var operand = AnalyzeExpression(args[0].Expression, varParams);
            if (operand is null) return null;

            return new PatternNode
            {
                OperationName = methodName,
                IsPrefixSemantic = true,
                OperatorString = unaryOp,
                Children = [operand]
            };
        }

        // 自定义操作（非标准二元/一元/字面量）
        var customNode = new PatternNode { OperationName = methodName };
        foreach (var arg in args)
        {
            var child = AnalyzeExpression(arg.Expression, varParams);
            if (child is not null)
                customNode.Children.Add(child);
            else
                customNode.Children.Add(new PatternNode { OperationName = "unknown" });
        }

        return customNode;
    }

    /// <summary>
    ///     分析 C# 二元运算符表达式
    /// </summary>
    private PatternNode? AnalyzeBinaryExpression(BinaryExpressionSyntax binaryExpr, HashSet<string> varParams)
    {
        var opName = MapCSharpBinaryOperator(binaryExpr.OperatorToken.Kind());
        if (opName is null) return null;

        var left = AnalyzeExpression(binaryExpr.Left, varParams);
        var right = AnalyzeExpression(binaryExpr.Right, varParams);

        if (left is null || right is null) return null;

        var opString = InfixOperatorMethodMap.TryGetValue(opName, out var mapped) ? mapped : opName.ToLowerInvariant();

        return new PatternNode
        {
            OperationName = opName,
            IsInfixSemantic = true,
            OperatorString = opString,
            Children = [left, right]
        };
    }

    /// <summary>
    ///     分析 C# 一元运算符表达式
    /// </summary>
    private PatternNode? AnalyzeUnaryExpression(PrefixUnaryExpressionSyntax unaryExpr, HashSet<string> varParams)
    {
        var opName = MapCSharpUnaryOperator(unaryExpr.OperatorToken.Kind());
        if (opName is null) return null;

        var operand = AnalyzeExpression(unaryExpr.Operand, varParams);
        if (operand is null) return null;

        var opString = PrefixOperatorMethodMap.TryGetValue(opName, out var mapped) ? mapped : opName.ToLowerInvariant();

        return new PatternNode
        {
            OperationName = opName,
            IsPrefixSemantic = true,
            OperatorString = opString,
            Children = [operand]
        };
    }

    /// <summary>
    ///     分析简化调用（无代数接口前缀的方法调用）
    /// </summary>
    private PatternNode? AnalyzeSimpleInvocation(
        string simpleName, MemberAccessExpressionSyntax memberAccess, HashSet<string> varParams)
    {
        if (LiteralNodeType.TryGetValue(simpleName, out var literalType))
            return new PatternNode
            {
                OperationName = simpleName,
                IsLiteral = true,
                LiteralNodeType = literalType
            };

        return null;
    }

    /// <summary>
    ///     获取方法调用表达式的目标方法名
    /// </summary>
    private static string? GetMethodName(InvocationExpressionSyntax invocation)
    {
        if (invocation.Expression is MemberAccessExpressionSyntax memberAccess)
            return memberAccess.Name.Identifier.Text;

        if (invocation.Expression is MemberBindingExpressionSyntax) return null;

        if (invocation.Expression is IdentifierNameSyntax identifier) return identifier.Identifier.Text;

        return null;
    }

    /// <summary>
    ///     映射 C# 二元运算符 → 方法名
    /// </summary>
    private static string? MapCSharpBinaryOperator(SyntaxKind kind)
    {
        return kind switch
        {
            SyntaxKind.PlusToken => "Add",
            SyntaxKind.MinusToken => "Sub",
            SyntaxKind.AsteriskToken => "Mul",
            SyntaxKind.SlashToken => "Div",
            SyntaxKind.PercentToken => "Mod",
            SyntaxKind.EqualsEqualsToken => "Eq",
            SyntaxKind.ExclamationEqualsToken => "Ne",
            SyntaxKind.LessThanToken => "Lt",
            SyntaxKind.LessThanEqualsToken => "Le",
            SyntaxKind.GreaterThanToken => "Gt",
            SyntaxKind.GreaterThanEqualsToken => "Ge",
            SyntaxKind.AmpersandAmpersandToken => "And",
            SyntaxKind.BarBarToken => "Or",
            SyntaxKind.CaretToken => "Xor",
            SyntaxKind.LessThanLessThanToken => "Shl",
            SyntaxKind.GreaterThanGreaterThanToken => "Shr",
            SyntaxKind.AmpersandToken => "Band",
            SyntaxKind.BarToken => "Bor",
            _ => null
        };
    }

    /// <summary>
    ///     映射 C# 一元运算符 → 方法名
    /// </summary>
    private static string? MapCSharpUnaryOperator(SyntaxKind kind)
    {
        return kind switch
        {
            SyntaxKind.MinusToken => "Neg",
            SyntaxKind.ExclamationToken => "Not",
            SyntaxKind.TildeToken => "Bitnot",
            _ => null
        };
    }

