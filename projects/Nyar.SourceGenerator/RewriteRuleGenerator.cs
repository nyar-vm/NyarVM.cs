        sb.AppendLine($"{indent}    var childNodes = egraph.get_nodes(childId);");
        sb.AppendLine($"{indent}    return op switch");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        \"add\" => childNodes.Any(n => n is Add),");
        sb.AppendLine($"{indent}        \"sub\" => childNodes.Any(n => n is Sub),");
