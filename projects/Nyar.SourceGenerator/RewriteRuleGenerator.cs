    /// <summary>
    ///     从语法树中收集所有重写规则对（模式+替换+守卫）
    /// </summary>
    private void CollectRulePairs(
        GeneratorExecutionContext context,
        SemanticModel semanticModel,
        SyntaxTree tree,
        List<RulePairInfo> rulePairs)
    {
        var root = tree.GetRoot();
        var allMethods = new List<MethodWithAttributes>();

        foreach (var methodDecl in root.DescendantNodes().OfType<MethodDeclarationSyntax>())
        {
            var methodSymbol = semanticModel.GetDeclaredSymbol(methodDecl);
            if (methodSymbol is null) continue;

            if (!methodSymbol.IsStatic) continue;

            var containingType = methodSymbol.ContainingType;
            if (containingType is null || !containingType.IsStatic) continue;

            var attrClassNames = methodSymbol.GetAttributes()
                .Select(a => a.AttributeClass?.ToDisplayString())
                .Where(n => n is not null)
                .ToList();
            allMethods.Add(new MethodWithAttributes(methodSymbol, attrClassNames!, methodDecl));
        }

        var ruleMethods = allMethods
            .Where(m => HasAttribute(m.AttributeClassNames, NewRuleAttrName) ||
                        HasAttribute(m.AttributeClassNames, OldRuleAttrName))
            .ToList();

        var replacementMethods = allMethods
            .Where(m => HasAttribute(m.AttributeClassNames, ReplacementAttrName))
            .ToList();

        var guardMethods = allMethods
            .Where(m => HasAttribute(m.AttributeClassNames, GuardAttrName))
            .ToList();

        foreach (var ruleMethod in ruleMethods)
        {
            var isNewAttr = ruleMethod.AttributeClassNames.Contains(NewRuleAttrName);
            var isOldAttr = ruleMethod.AttributeClassNames.Contains(OldRuleAttrName);

            var ruleName = ruleMethod.Symbol.Name;
            string? dialect = null;

            if (isNewAttr)
            {
                var attr = ruleMethod.Symbol.GetAttributes()
                    .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == NewRuleAttrName);
                if (attr is not null)
                {
                    ruleName = attr.NamedArguments
                                   .FirstOrDefault(kvp =>
                                       string.Equals(kvp.Key, "name", StringComparison.OrdinalIgnoreCase)).Value
                                   .Value as string
                               ?? ruleName;
                    dialect = attr.NamedArguments
                        .FirstOrDefault(kvp => string.Equals(kvp.Key, "Dialect", StringComparison.OrdinalIgnoreCase))
                        .Value.Value as string;
                }
            }
            else if (isOldAttr)
            {
                var attr = ruleMethod.Symbol.GetAttributes()
                    .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == OldRuleAttrName);
                if (attr is not null) ruleName = attr.ConstructorArguments.FirstOrDefault().Value as string ?? ruleName;
            }

            var containingType = ruleMethod.Symbol.ContainingType;
            var ns = containingType.ContainingNamespace?.ToDisplayString() ?? string.Empty;
            var typeName = containingType.Name;

            var replacementMethod = FindMatchingReplacement(
                replacementMethods, ruleName, containingType, ruleMethod.Symbol);
            if (replacementMethod is null) continue;

            var guardMethod = FindMatchingGuard(
                guardMethods, ruleName, containingType, ruleMethod.Symbol);

            var patternTree = AnalyzePatternMethod(ruleMethod);
            if (patternTree is null) continue;

            var classKey = $"{ns}|{typeName}";

            rulePairs.Add(new RulePairInfo(
                ruleName,
                dialect,
                ruleMethod.Symbol.Name,
                replacementMethod.Symbol.Name,
                guardMethod?.Symbol.Name,
                ns,
                typeName,
                classKey,
                patternTree,
                ruleMethod.Syntax,
                replacementMethod.Syntax,
                guardMethod?.Syntax));
        }
    }

    private static bool HasAttribute(List<string> attributeClassNames, string fullName)
    {
        return attributeClassNames.Contains(fullName);
    }

    /// <summary>
    ///     查找与模式方法配对的替换方法
    /// </summary>
    private static MethodWithAttributes? FindMatchingReplacement(
        List<MethodWithAttributes> candidates,
        string ruleName,
        INamedTypeSymbol containingType,
        IMethodSymbol ruleMethod)
    {
        foreach (var candidate in candidates)
        {
            if (!SymbolEqualityComparer.Default.Equals(candidate.Symbol.ContainingType, containingType)) continue;

            var replacementAttr = candidate.Symbol.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == ReplacementAttrName);

            if (replacementAttr is null) continue;

            var patternParam = replacementAttr.NamedArguments
                .FirstOrDefault(kvp => string.Equals(kvp.Key, "pattern", StringComparison.OrdinalIgnoreCase)).Value
                .Value as string;

            if (patternParam is not null)
            {
                if (string.Equals(patternParam, ruleName, StringComparison.Ordinal) ||
                    string.Equals(patternParam, ruleMethod.Name, StringComparison.Ordinal))
                    return candidate;
            }
            else
            {
                // 按命名约定查找：PatternMethod + "Replacement" 或暗含匹配
                if (string.Equals(candidate.Symbol.Name, ruleMethod.Name + "Replacement",
                        StringComparison.OrdinalIgnoreCase))
                    return candidate;
            }
        }

        return null;
    }

    /// <summary>
    ///     查找与模式方法配对的守卫方法
    /// </summary>
    private static MethodWithAttributes? FindMatchingGuard(
        List<MethodWithAttributes> candidates,
        string ruleName,
        INamedTypeSymbol containingType,
        IMethodSymbol ruleMethod)
    {
        foreach (var candidate in candidates)
        {
            if (!SymbolEqualityComparer.Default.Equals(candidate.Symbol.ContainingType, containingType)) continue;

            var guardAttr = candidate.Symbol.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == GuardAttrName);

            if (guardAttr is null) continue;

            var patternParam = guardAttr.NamedArguments
                .FirstOrDefault(kvp => string.Equals(kvp.Key, "pattern", StringComparison.OrdinalIgnoreCase)).Value
                .Value as string;

            if (patternParam is not null)
            {
                if (string.Equals(patternParam, ruleName, StringComparison.Ordinal) ||
                    string.Equals(patternParam, ruleMethod.Name, StringComparison.Ordinal))
                    return candidate;
            }
            else
            {
                if (string.Equals(candidate.Symbol.Name, ruleMethod.Name + "Guard",
                        StringComparison.OrdinalIgnoreCase))
                    return candidate;
            }
        }

        return null;
    }

