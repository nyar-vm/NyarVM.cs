    /// <summary>
    ///     获取 OA 二元运算匹配类型名，若不在 OA 映射中则返回 null
    /// </summary>
    private static string? GetCoreInfixNodeTypeName(string op)
    {
        return op switch
        {
            "add" => "Add",
            "sub" => "Sub",
            "mul" => "Mul",
            "div" => "Div",
            "eq" or "ne" or "lt" or "le" or "gt" or "ge" => "Cmp",
            "and" => "And",
            "or" => "Or",
            _ => null
        };
    }

    /// <summary>
    ///     获取 OA 一元运算匹配类型名，若不在 OA 映射中则返回 null
    /// </summary>
    private static string? GetCorePrefixNodeTypeName(string op)
    {
        return op switch
        {
            "neg" => "Neg",
            "not" => "Not",
            _ => null
        };
    }

    /// <summary>
    ///     获取比较运算符对应的 CompareOp 表达式
    /// </summary>
    private static string? GetCompareOpExpr(string op)
    {
        return op switch
        {
            "eq" => "CompareOp.eq",
            "ne" => "CompareOp.ne",
            "lt" => "CompareOp.lt",
            "le" => "CompareOp.le",
            "gt" => "CompareOp.gt",
            "ge" => "CompareOp.ge",
            _ => null
        };
    }

    /// <summary>
    ///     获取 OA 二元运算匹配的完整模式字符串
    /// </summary>
    /// <param name="op">运算符字符串。</param>
    /// <param name="leftVar">左操作数变量名（不含 var 前缀）。</param>
    /// <param name="rightVar">右操作数变量名（不含 var 前缀）。</param>
    /// <param name="withVar">是否在模式中加上 var 关键字。</param>
    /// <returns>匹配模式字符串；若不在 OA 映射中则返回 null。</returns>
    private static string? GetCoreInfixMatchPattern(string op, string leftVar, string rightVar, bool withVar)
    {
        var varPrefix = withVar ? "var " : "";
        var typeName = GetCoreInfixNodeTypeName(op);
        if (typeName is null) return null;

        if (typeName == "Cmp")
        {
            var cmpExpr = GetCompareOpExpr(op);
            return $"Cmp {{ op: {cmpExpr}, left: {varPrefix}{leftVar}, right: {varPrefix}{rightVar} }}";
        }

        return $"{typeName} {{ left: {varPrefix}{leftVar}, right: {varPrefix}{rightVar} }}";
    }

    /// <summary>
    ///     获取 OA 一元运算匹配的完整模式字符串
    /// </summary>
    /// <param name="op">运算符字符串。</param>
    /// <param name="operandVar">操作数变量名（不含 var 前缀）。</param>
    /// <param name="withVar">是否在模式中加上 var 关键字。</param>
    /// <returns>匹配模式字符串；若不在 OA 映射中则返回 null。</returns>
    private static string? GetCorePrefixMatchPattern(string op, string operandVar, bool withVar)
    {
        var varPrefix = withVar ? "var " : "";
        var typeName = GetCorePrefixNodeTypeName(op);
        if (typeName is null) return null;

        return $"{typeName} {{ operand: {varPrefix}{operandVar} }}";
    }

