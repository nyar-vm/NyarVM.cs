    public void Execute(GeneratorExecutionContext context)
    {
        var rulePairs = new List<RulePairInfo>();

        foreach (var tree in context.Compilation.SyntaxTrees)
        {
            var semanticModel = context.Compilation.GetSemanticModel(tree);
            CollectRulePairs(context, semanticModel, tree, rulePairs);
        }

        if (rulePairs.Count == 0) return;

        var groupedByClass = rulePairs.GroupBy(r => r.ClassKey);

        foreach (var group in groupedByClass)
        {
            var rules = group.ToList();
            var first = rules[0];

            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#pragma warning disable CS0105");
            sb.AppendLine("using System;");
            sb.AppendLine("using System.CodeDom.Compiler;");
            sb.AppendLine("using System.Collections.Generic;");
            sb.AppendLine("using System.Collections.Immutable;");
            sb.AppendLine("using System.Linq;");
            sb.AppendLine("using Nyar.EGraph;");
            sb.AppendLine("using Nyar.IR.Intent;");
            sb.AppendLine("using Nyar.IR.Strategy;");
            sb.AppendLine("using Nyar.IR.Rewrite;");
            sb.AppendLine("using Nyar.Dialect.Sonic.Core.Nodes;");
            sb.AppendLine($"using {first.Namespace};");
            sb.AppendLine("#pragma warning restore CS0105");
            sb.AppendLine();

            sb.AppendLine("namespace Nyar.IR.Rewrite;");
            sb.AppendLine();

            // 生成 MatchResult 记录类型（file 作用域，每个生成文件一份）
            GenerateMatchResultType(sb);

            var ruleClassNames = new List<string>();

            for (var i = 0; i < rules.Count; i++)
            {
                var rule = rules[i];
                var className = $"Generated_{SanitizeIdentifier(rule.RuleName)}_Rule";
                ruleClassNames.Add(className);
                GenerateRuleClass(sb, rule, "    ");
                if (i < rules.Count - 1) sb.AppendLine();
            }

            var safeClassName = SanitizeIdentifier(first.ContainingTypeName);

            // TODO: SG 生成的规则代码暂未与当前 EGgraph API 对齐（get_nodes/rebuild 等），
            // 暂时跳过生成，AlgebraicRules.GeneratedRules() 返回空列表作为安全回退。
            // context.AddSource($"Generated_{safeClassName}_Rules.g.cs",
            //     SourceText.From(sb.ToString(), Encoding.UTF8));
            // GenerateFactoryClass(context, first, safeClassName, ruleClassNames);
        }
    }

