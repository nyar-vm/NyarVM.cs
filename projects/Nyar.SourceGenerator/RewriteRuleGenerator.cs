    /// <summary>
    ///     收集模式树中所有变量名
    /// </summary>
    private static HashSet<string> CollectVarNames(PatternNode node)
    {
        var vars = new HashSet<string>(StringComparer.Ordinal);
        CollectVarNamesRecursive(node, vars);
        return vars;
    }

    private static void CollectVarNamesRecursive(PatternNode node, HashSet<string> vars)
    {
        if (node.IsVarReference) vars.Add(node.VarName!);

        foreach (var child in node.Children) CollectVarNamesRecursive(child, vars);
    }

    /// <summary>
    ///     清理标识符中不允许的字符
    /// </summary>
    private static string SanitizeIdentifier(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name)
            if (char.IsLetterOrDigit(ch) || ch == '_')
                sb.Append(ch);
            else
                sb.Append('_');

        if (sb.Length == 0) return "_";

        if (char.IsDigit(sb[0])) sb.Insert(0, '_');

        return sb.ToString();
    }

    /// <summary>
    ///     转义 C# 字符串字面量
    /// </summary>
    private static string EscapeCSharpString(string value)
    {
        return value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\n", "\\n")
            .Replace("\r", "\\r")
            .Replace("\t", "\\t");
    }

