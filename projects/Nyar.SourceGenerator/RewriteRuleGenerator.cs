        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    var childNodes = egraph.get_nodes(childId);");
        sb.AppendLine(
            $"{indent}    return childNodes.Any(n => n is StrategyNode.Extension {{ Name: var __n }} && __n == name);");
        sb.AppendLine($"{indent}}}");
    }

