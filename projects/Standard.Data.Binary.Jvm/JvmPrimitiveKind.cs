namespace Std.Data.Binary.Jvm;

/// <summary>
///     JVM 原始类型种类枚举。
/// </summary>
public enum JvmPrimitiveKind
{
    /// <summary>
    ///     无返回值类型。
    /// </summary>
    @void,

    /// <summary>
    ///     布尔类型。
    /// </summary>
    @boolean,

    /// <summary>
    ///     字节类型。
    /// </summary>
    @byte,

    /// <summary>
    ///     短整型。
    /// </summary>
    @short,

    /// <summary>
    ///     整型。
    /// </summary>
    @int,

    /// <summary>
    ///     长整型。
    /// </summary>
    @long,

    /// <summary>
    ///     单精度浮点类型。
    /// </summary>
    @float,

    /// <summary>
    ///     双精度浮点类型。
    /// </summary>
    @double,

    /// <summary>
    ///     字符类型。
    /// </summary>
    @char
}
