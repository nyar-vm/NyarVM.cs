    #region 数据模型

    /// <summary>
    ///     目标语言枚举，与 Sonic.Core 中定义的 <c>TargetLanguage</c> 对应。
    /// </summary>
    internal enum TargetLanguage
    {
        /// <summary>
        ///     TypeScript 语言。
        /// </summary>
        type_script = 0,

        /// <summary>
        ///     Python 语言。
        /// </summary>
        python = 1,

        /// <summary>
        ///     Java 语言。
        /// </summary>
        java = 2,

        /// <summary>
        ///     Go 语言。
        /// </summary>
        go = 3,

        /// <summary>
        ///     Rust 语言。
        /// </summary>
        rust = 4,

        /// <summary>
        ///     Swift 语言。
        /// </summary>
        swift = 5,

        /// <summary>
        ///     Kotlin 语言。
        /// </summary>
        kotlin = 6,

        /// <summary>
        ///     JavaScript 语言。
        /// </summary>
        java_script = 7,

        /// <summary>
        ///     C++ 语言。
        /// </summary>
        cpp = 8
    }

    /// <summary>
    ///     需要生成转译代码的类型信息。
    /// </summary>
    internal readonly struct TranspileTypeInfo
    {
        /// <summary>
        ///     类型名称。
        /// </summary>
        public readonly string type_name;

        /// <summary>
        ///     完全限定类型名称。
        /// </summary>
        public readonly string fully_qualified_name;

        /// <summary>
        ///     命名空间名称。
        /// </summary>
        public readonly string? namespace_name;

        /// <summary>
        ///     是否为结构体。
        /// </summary>
        public readonly bool is_struct;

        /// <summary>
        ///     目标语言列表。
        /// </summary>
        public readonly List<int> target_languages;

        /// <summary>
        ///     类型成员列表。
        /// </summary>
        public readonly List<TranspileMemberInfo> members;

        /// <summary>
        ///     初始化 <see cref="TranspileTypeInfo" /> 的新实例。
        /// </summary>
        public TranspileTypeInfo(
            string typeName,
            string fullyQualifiedName,
            string? namespaceName,
            bool isStruct,
            List<int> targetLanguages,
            List<TranspileMemberInfo> members)
        {
            type_name = typeName;
            fully_qualified_name = fullyQualifiedName;
            namespace_name = namespaceName;
            is_struct = isStruct;
            target_languages = targetLanguages;
            this.members = members;
        }
    }

    /// <summary>
    ///     转译类型成员信息。
    /// </summary>
    internal readonly struct TranspileMemberInfo
    {
        /// <summary>
        ///     成员名称。
        /// </summary>
        public readonly string name;

        /// <summary>
        ///     完全限定类型名称。
        /// </summary>
        public readonly string fully_qualified_type;

        /// <summary>
        ///     特殊类型。
        /// </summary>
        public readonly SpecialType special_type;

        /// <summary>
        ///     初始化 <see cref="TranspileMemberInfo" /> 的新实例。
        /// </summary>
        public TranspileMemberInfo(string name, string fullyQualifiedType, SpecialType specialType)
        {
            this.name = name;
            fully_qualified_type = fullyQualifiedType;
            special_type = specialType;
        }
    }

    #endregion
}