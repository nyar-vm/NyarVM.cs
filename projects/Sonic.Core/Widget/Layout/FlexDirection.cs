namespace Core.Widget.Layout;

/// <summary>
///     FlexDirection 枚举
/// </summary>
public enum FlexDirection
{
    /// <summary>
    ///     水平排列
    /// </summary>
    row,

    /// <summary>
    ///     垂直排列
    /// </summary>
    column,

    /// <summary>
    ///     水平反向排列
    /// </summary>
    row_reverse,

    /// <summary>
    ///     垂直反向排列
    /// </summary>
    column_reverse
}