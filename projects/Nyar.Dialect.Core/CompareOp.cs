namespace Nyar.Dialect.Core;

/// <summary>
///     比较操作符枚举
/// </summary>
public enum CompareOp
{
    /// <summary>
    ///     等于
    /// </summary>
    eq,

    /// <summary>
    ///     不等于
    /// </summary>
    ne,

    /// <summary>
    ///     小于
    /// </summary>
    lt,

    /// <summary>
    ///     小于等于
    /// </summary>
    le,

    /// <summary>
    ///     大于
    /// </summary>
    gt,

    /// <summary>
    ///     大于等于
    /// </summary>
    ge
}